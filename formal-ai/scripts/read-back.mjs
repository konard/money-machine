#!/usr/bin/env node
/**
 * Measure the EN → meta → RU → meta round trip over the fixture sentences,
 * replayed offline: each Russian translation is read back
 * (src/russian/read-back.mjs) and compared with the meta links it came
 * from. Writes docs/russian-read-back.md.
 *
 *   node formal-ai/scripts/read-back.mjs [--write]
 */
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { productionEnv, sentenceSet, BASIC } from './record-fixtures.mjs';

const cache = mkdtempSync(join(tmpdir(), 'formal-ai-read-back-'));
Object.assign(
  process.env,
  productionEnv({ FORMAL_AI_OFFLINE: '1', FORMAL_AI_CACHE: cache })
);
try {
  const { loadLexicon } = await import('../src/lexicon.mjs');
  const { resolveText } = await import('../src/resolve.mjs');
  const { translateDocument } = await import('../src/document.mjs');
  const { readBack, russianFormIndex } =
    await import('../src/russian/read-back.mjs');
  const { englishRoundTrip } = await import('../src/english/round-trip.mjs');
  const { pages } = await import('./sample.mjs');
  const { fixtureFetch } = await import('./evaluate.mjs');
  const sources = JSON.parse(
    readFileSync(new URL('./fixture-sentences.json', import.meta.url), 'utf8')
  );
  const topics = new Map(pages().map((p) => [p.source, p.text]));
  const sentences = sentenceSet();
  let lexicon = loadLexicon({ fresh: true });
  try {
    await resolveText(sentences.join('\n\n'), { lexicon });
  } catch (error) {
    if (!error.offline) {
      throw error;
    }
    lexicon = loadLexicon({ fresh: true });
    await resolveText(sentences.join('\n\n'), {
      lexicon,
      fetchImpl: fixtureFetch(),
    });
  }
  const index = russianFormIndex(lexicon);
  const status = {};
  const changes = {};
  const added = {};
  const unread = {};
  const failing = [];
  let survive = 0;
  let english = 0;
  let textSame = 0;
  const rewritten = [];
  const norm = (t) =>
    t
      .toLowerCase()
      .replace(/[^\p{L}\d$]+/gu, ' ')
      .trim();
  let circle = 0;
  let total = 0;
  sentences.forEach((source, i) => {
    const translated = translateDocument(source, {
      lexicon,
      topic: topics.get(sources[i - BASIC.length]?.source),
    });
    for (const s of translated.sentences) {
      if (!s.formal || !s.complete) {
        continue;
      }
      total += 1;
      const r = readBack(s.text, s.formal, lexicon, index);
      survive += Number(r.survives);
      // the full circle EN → meta → RU → meta → EN: the Russian keeps the
      // meta links and the meta links give back the English they came from
      const trip = englishRoundTrip(s.source, lexicon);
      const back = trip.exact;
      // links can agree with themselves while both parses lose a meaning
      // ("don't market or set" → set positive); the text cannot
      const same = norm(trip.english) === norm(s.source);
      textSame += Number(same);
      if (!same) {
        rewritten.push(`${s.source} → ${trip.english}`);
      }
      english += Number(back);
      circle += Number(back && r.survives);
      for (const l of r.links) {
        status[l.status] = (status[l.status] || 0) + 1;
        for (const c of l.changes || []) {
          const kind = c.split(' ')[0];
          changes[kind] = (changes[kind] || 0) + 1;
        }
      }
      r.added.forEach((w) => (added[w] = (added[w] || 0) + 1));
      r.unread.forEach((w) => (unread[w] = (unread[w] || 0) + 1));
      if (!r.survives) {
        failing.push({
          english: s.source,
          russian: s.text,
          problems: [
            ...r.links
              .filter((l) => !['kept', 'widened'].includes(l.status))
              .map(
                (l) =>
                  `${l.status} ${l.concept || l.name}${l.word ? ` (${l.word})` : ''}${l.changes ? `: ${l.changes.join('; ')}` : ''}`
              ),
            ...r.added.map((w) => `added ${w}`),
          ],
        });
      }
    }
  });
  const pct = (n) => `${((n / Math.max(1, total)) * 100).toFixed(1)}%`;
  const top = (counts, n = 15) =>
    Object.entries(counts)
      .sort((a, b) => b[1] - a[1])
      .slice(0, n)
      .map(([k, v]) => `${k} (${v})`)
      .join(', ') || '—';
  const lines = [
    '# Russian read-back: EN → meta → RU → meta',
    '',
    'Generated by `node formal-ai/scripts/read-back.mjs --write` over the complete fixture sentences, replayed offline. Each Russian translation is read back word by word to the range of meanings its forms carry (`src/russian/read-back.mjs`) and compared with the meta links it was generated from. A sentence survives when every source link is still readable — the same concept, noun number, tense, polarity and quantity — and no content word reads as a meaning the source did not have. "Widened" links are readable but the Russian word carries a wider range of meanings than the one chosen; they count as surviving, the vagueness is the text\'s own. This checks the Russian side against the meta language, not the meta language against the English (that is the English round trip) nor the sense choice itself.',
    '',
    `- Sentences: ${total}; Russian read-back survives: ${survive} (${pct(survive)})`,
    `- English round trip (EN → meta → EN) exact: ${english} (${pct(english)}); full circle EN → meta → RU → meta → EN (both): ${circle} (${pct(circle)})`,
    `- English text regenerated word for word from the meta: ${textSame} (${pct(textSame)})`,
    `- Links by status: ${top(status)}`,
    `- Changed grammar: ${top(changes)}`,
    `- Content words with a meaning not in the source: ${top(added)}`,
    `- Words the lexicon cannot read: ${top(unread)}`,
    '',
    '## English regenerated differently',
    '',
    'Either a paraphrase with the same meaning (contractions, word order) or a meaning the meta language lost or added; each is a lead for the English analyser.',
    '',
    ...rewritten.map((r) => `- ${r}`),
    '',
    '## Sentences that do not survive',
    '',
    ...failing.flatMap((f) => [
      `- ${f.english}`,
      `  - ${f.russian}`,
      ...f.problems.map((p) => `  - ${p}`),
    ]),
    '',
  ];
  const text = lines.join('\n');
  if (process.argv.includes('--write')) {
    writeFileSync(
      new URL('../docs/russian-read-back.md', import.meta.url),
      text
    );
  }
  process.stdout.write(text);
} finally {
  rmSync(cache, { recursive: true, force: true });
}
